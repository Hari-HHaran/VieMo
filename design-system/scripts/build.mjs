// Builds the VieMo design system from its sources:
//   components/bundle.js   classic script for the design-system page (window.VieMo, needs window.React)
//   components/viemo.mjs   ES module for apps (imports react)
//   components/viemo.d.mts types for the ES module
//   tokens.css             custom properties, type classes and @font-face from tokens.json
// Run: node design-system/scripts/build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
const write = (p, s) => writeFileSync(join(root, p), s);

const icons = read('src/icons.js').trim();
const source = read('src/components.js');
const NAMES = ['Button', 'Icon', 'Avatar', 'Poster', 'FilmCard', 'Rating', 'ReviewCard', 'ActivityItem', 'ProfilePreview',
  'ProviderBadge', 'CollectionTile', 'SwipeCard', 'FilterChip', 'BottomNav', 'Skeleton', 'EmptyState', 'ErrorState',
  'ConfirmModal', 'Toast', 'AccentPicker'];

const header = '/* @ds-bundle: ' + JSON.stringify({ format: 4, namespace: 'VieMo', components: NAMES.map((name) => ({ name })) }) + ' */';
const classic = [header,
  '/* VieMo components for React 18+ (window.React, window.ReactDOM). Icons: Lucide 0.460.0, ISC licence. Generated by scripts/build.mjs. */',
  '(function () {', '  "use strict";', '  ' + icons, source, '})();', ''].join('\n');
if (/<\/script|<!--/i.test(classic)) throw new Error('bundle.js must not contain </script or <!--');
write('components/bundle.js', classic);

const reactLine = '  var React = window.React;\n';
const globalLine = '  window.VieMo = Object.assign(window.VieMo || {}, api);\n';
if (!source.includes(reactLine) || !source.includes(globalLine)) throw new Error('components.js header or footer changed; update build.mjs');
const exported = ['Button', 'Icon', 'Avatar', 'Poster', 'FilmCard', 'ReviewCard', 'ActivityItem', 'ProfilePreview', 'ProviderBadge',
  'CollectionTile', 'SwipeCard', 'Rating', 'FilterChip', 'BottomNav', 'Skeleton', 'EmptyState', 'ErrorState', 'ConfirmModal',
  'Toast', 'AccentPicker', 'AccentScope', 'deriveAccent', 'applyAccent', 'accentCss', 'extractSwatches', 'colorName', 'contrast',
  'formatRuntime'];
const esm = ['/* VieMo components as an ES module. Generated by design-system/scripts/build.mjs from src/; do not edit. */',
  "import * as React from 'react';", icons,
  source.replace(reactLine, '').replace(globalLine, ''),
  'export { ' + exported.join(', ') + ' };',
  'export var iconNames = Object.keys(ICONS);',
  'export default api;', ''].join('\n');
write('components/viemo.mjs', esm);
write('components/viemo.d.mts', read('components/index.d.ts') +
  '\nexport declare const iconNames: IconName[];\nexport declare function formatRuntime(minutes: number | null | undefined): string | null;\ndeclare const api: Window["VieMo"];\nexport default api;\n');

// tokens.css, laid out like the design-system page compiles it.
const T = JSON.parse(read('tokens.json'));
const themes = T.color.themes.map((t) => t.id);
const val = (x) => (typeof x === 'string' && x.startsWith('{') ? `var(--${x.slice(1, -1)})` : x);
const per = (tok, th) => (typeof tok.value === 'string' ? (th === themes[0] ? val(tok.value) : null) : tok.value[th] != null ? val(tok.value[th]) : null);
const out = [`/* ${T.name} — generated from tokens.json */`];
for (const f of T.type.fonts) out.push(`@font-face { font-family: '${f.family}'; src: url('${f.file}') format('woff2'); font-weight: ${f.weight}; font-style: ${f.style || 'normal'}; font-display: swap; }`);
const themed = [...T.color.tokens, ...(T.shadow?.tokens || [])];
out.push(`:root, [data-theme="${themes[0]}"] {\n${themed.map((t) => `  --${t.name}: ${per(t, themes[0])};`).join('\n')}\n}`);
for (const th of themes.slice(1)) {
  const lines = themed.map((t) => [t, per(t, th) ?? (typeof t.value === 'string' && t.value.startsWith('{') ? val(t.value) : null)]).filter(([, v]) => v != null);
  out.push(`[data-theme="${th}"] {\n${lines.map(([t, v]) => `  --${t.name}: ${v};`).join('\n')}\n}`);
}
const flat = [];
for (const [k, fam] of Object.entries(T)) if (!['name', 'version', 'color', 'type', 'shadow'].includes(k) && fam?.tokens) for (const t of fam.tokens) flat.push(`  --${t.name}: ${t.value};`);
for (const [k, s] of Object.entries(T.type.families)) flat.push(`  --font-${k}: ${s};`);
out.push(`:root {\n${flat.join('\n')}\n}`);
for (const g of T.type.groups) for (const s of g.styles) {
  const d = [`font-family: var(--font-${s.family || g.family})`, `font-size: ${s.fontSize}`, `line-height: ${s.lineHeight}`, `font-weight: ${s.fontWeight}`];
  if (s.letterSpacing) d.push(`letter-spacing: ${s.letterSpacing}`);
  out.push(`.${s.name} { ${d.join('; ')}; }`);
}
write('tokens.css', out.join('\n') + '\n');
console.log('built bundle.js, viemo.mjs, viemo.d.mts, tokens.css');
