// Generates src/app/worlds.css: one colour world per destination, applied with data-world on the app shell.
// Each world sets its own grounds (dark theme) and an accent tuned by the design system's deriveAccent, then
// every text and control pair is checked; the script fails rather than write a world below WCAG AA.
//   node scripts/worlds.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { deriveAccent, contrast } from '../design-system/components/viemo.mjs';

/* The palette lives in src/lib/worlds.json so the film page can tune poster accents against the same grounds. */
const data = JSON.parse(readFileSync(new URL('../src/lib/worlds.json', import.meta.url), 'utf8'));
const { ink: INK, muted: MUTED, faint: FAINT } = data.ink;
const LIGHT = data.light;
const WORLDS = Object.fromEntries(Object.entries(data.worlds).map(([k, w]) => [k, { g: w.grounds, seed: w.seed, note: w.note }]));


const fails = [];
const check = (world, label, a, b, min) => { const c = contrast(a, b); if (c < min) fails.push(`${world}: ${label} ${c.toFixed(2)} < ${min}`); };
const out = ['/* VieMo worlds. Generated by scripts/worlds.mjs; do not edit by hand. */'];
const keys = ['bg', 'surface', 'surface-raised', 'surface-overlay', 'line', 'line-strong', 'skeleton'];

for (const [name, w] of Object.entries(WORLDS)) {
  const g = Object.fromEntries(keys.map((k, i) => [k, w.g[i]]));
  const dark = { bg: g.bg, surface: g.surface, 'surface-raised': g['surface-raised'], 'surface-overlay': g['surface-overlay'], ink: INK };
  const a = deriveAccent(w.seed, { grounds: { dark, light: LIGHT } });
  for (const s of ['bg', 'surface', 'surface-raised', 'surface-overlay']) {
    check(name, `ink on ${s}`, INK, g[s], 4.5);
    check(name, `ink-muted on ${s}`, MUTED, g[s], 4.5);
    check(name, `line-strong on ${s}`, g['line-strong'], g[s], 3);
    check(name, `reel-ink on ${s}`, a.dark['reel-ink'], g[s], 4.5);
  }
  for (const s of ['bg', 'surface', 'surface-raised']) {
    check(name, `ink-faint on ${s}`, FAINT, g[s], 4.5);
    check(name, `reel fill on ${s}`, a.dark.reel, g[s], 3);
  }
  check(name, 'on-reel on reel', a.dark['on-reel'], a.dark.reel, 4.5);
  check(name, 'ink on reel-soft', INK, a.dark['reel-soft'], 4.5);

  const roles = (t) => `--reel: ${t.reel}; --on-reel: ${t['on-reel']}; --reel-ink: ${t['reel-ink']}; --reel-soft: ${t['reel-soft']};`;
  out.push(`/* ${w.note} */`);
  out.push(`:is(.shell, .curtain)[data-world="${name}"] { ${keys.map((k) => `--${k}: ${g[k]};`).join(' ')} --world-seed: ${w.seed}; ${roles(a.dark)} }`);
  out.push(`[data-theme="light"] :is(.shell, .curtain)[data-world="${name}"] { ${keys.map((k) => `--${k}: inherit;`).join(' ')} ${roles(a.light)} }`);
}
/* The Green Room (Profile) is the one place a person's own accent (from their favourite film) shows. */
out.push('html[data-vm-accent] .shell[data-world="greenroom"] { --reel: inherit; --on-reel: inherit; --reel-ink: inherit; --reel-soft: inherit; }');

if (fails.length) { console.error('Contrast failures:\n' + fails.join('\n')); process.exit(1); }
writeFileSync(new URL('../src/app/worlds.css', import.meta.url), out.join('\n') + '\n');
console.log(`worlds.css: ${Object.keys(WORLDS).length} worlds, every pair at WCAG AA`);
